#!/usr/bin/env python3
"""Stamp a content hash into index.html asset URLs and regenerate sw.js.

Run after any change to the app:  python3 tools/release.py
The service worker pre-caches every file the app needs (including audio),
so the app works offline after the first visit over HTTPS.
"""
import hashlib
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = [
    'css/app.css', 'js/text.js', 'js/app.js',
    'data/lessons.js', 'data/strokes.js', 'data/chars.js', 'data/audio.js',
    'vendor/hanzi-writer.min.js', 'vendor/pinyin-pro.js',
]
STATIC = ['manifest.webmanifest', 'icon.svg', 'icon-180.png', 'icon-192.png', 'icon-512.png']


def main():
    audio = sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / 'audio').glob('*.mp3'))
    h = hashlib.sha1()
    for rel in ASSETS + STATIC + audio:
        h.update(rel.encode())
        h.update((ROOT / rel).read_bytes())
    ver = h.hexdigest()[:10]

    index = ROOT / 'index.html'
    html = index.read_text(encoding='utf-8')
    html = re.sub(r'((?:href|src)="(?:css|js|data|vendor)/[^"?]+)(?:\?v=[^"]*)?"', rf'\1?v={ver}"', html)
    index.write_text(html, encoding='utf-8')

    core = ['./', 'index.html'] + [f'{a}?v={ver}' for a in ASSETS] + STATIC
    precache = core + audio
    sw = f"""/* generated by tools/release.py — do not edit */
const VERSION = 'hz-{ver}';
const CORE = {json.dumps(core, ensure_ascii=False)};
const MEDIA = {json.dumps(audio, ensure_ascii=False)};

// Core files must all cache; audio is best-effort (one retry), misses get cached on first play.
async function cacheOne(c, url) {{
  for (let i = 0; i < 2; i++) {{
    try {{ const res = await fetch(url, {{ cache: 'no-cache' }}); if (res.ok) {{ await c.put(url, res); return; }} }} catch (e) {{ /* retry */ }}
    await new Promise((r) => setTimeout(r, 800));
  }}
}}
self.addEventListener('install', (e) => {{
  e.waitUntil((async () => {{
    const c = await caches.open(VERSION);
    await c.addAll(CORE);
    for (let i = 0; i < MEDIA.length; i += 6) await Promise.all(MEDIA.slice(i, i + 6).map((u) => cacheOne(c, u)));
    await self.skipWaiting();
  }})());
}});

self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('hz-') && k !== VERSION).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (req.mode === 'navigate') {{
    // network first for the page itself so new releases show up, cache when offline
    e.respondWith(fetch(req).then((res) => {{
      const copy = res.clone();
      caches.open(VERSION).then((c) => c.put('index.html', copy));
      return res;
    }}).catch(() => caches.match('index.html')));
    return;
  }}
  const sameOrigin = url.origin === self.location.origin;
  const strokeCdn = url.hostname === 'cdn.jsdelivr.net' && url.pathname.includes('hanzi-writer-data');
  if (!sameOrigin && !strokeCdn) return;
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req).then((res) => {{
    if (res.ok && (sameOrigin || strokeCdn)) {{ const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); }}
    return res;
  }})));
}});
"""
    (ROOT / 'sw.js').write_text(sw, encoding='utf-8')
    print(f'version {ver}: {len(precache)} files pre-cached')


if __name__ == '__main__':
    main()
